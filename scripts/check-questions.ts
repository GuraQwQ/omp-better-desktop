import assert from 'node:assert/strict';
import { answerableQuestion, completeQuestion, createQuestionDraft, questionDraft, updateQuestionDraft } from '../src/lib/question-draft';
import { applyEvent, isSessionRunning } from '../src/lib/session-state';
import type { Json, SessionView } from '../src/lib/types';

const ask: Json = { type: 'extension_ui_request', method: 'ask', id: 'question-1', async: true, questions: [{ id: 'target', recommended: 0, options: [{ label: 'A' }] }] };
const session = (id: string): SessionView => ({ id, cwd: '/project', path: '/one.jsonl', messages: [], pending: [], status: 'running', state: { isStreaming: true, isSettled: false } });
let first = updateQuestionDraft(applyEvent(session('first'), ask), ask.id, draft => ({ ...draft, value: '保留输入' }));
assert.equal(isSessionRunning(first), true);
assert.deepEqual(createQuestionDraft(ask).answers, {});
assert.equal(questionDraft(applyEvent(session('second'), ask), ask).value, '');
assert.equal(applyEvent(first, { ...ask }), first);
first = updateQuestionDraft(first, ask.id, draft => ({ ...draft, submitting: true }));
assert.equal(answerableQuestion(first, ask.id), undefined);
first = updateQuestionDraft(first, ask.id, draft => ({ ...draft, submitting: false, error: '重试' }));
assert.equal(answerableQuestion(first, ask.id), ask);
assert.equal(questionDraft(first, ask).value, '保留输入');
const other = { ...ask, id: 'question-2' };
first = updateQuestionDraft(applyEvent(first, other), other.id, draft => ({ ...draft, value: '另一份草稿' }));
assert.equal(completeQuestion(first, ask).questionDrafts?.[other.id].value, '另一份草稿');
const replaced = applyEvent(first, { ...ask, title: '新请求' });
assert.equal(replaced.questionDrafts?.[ask.id], undefined);
assert.equal(completeQuestion(replaced, ask), replaced);
const ended = applyEvent(first, { type: 'desktop_status', status: 'disconnected' });
assert.deepEqual(ended.pending, []);
assert.equal(ended.questionDrafts, undefined);
assert.equal(applyEvent(ended, ask), ended);
assert.equal(applyEvent(first, { type: 'session_settled' }).questionDrafts, first.questionDrafts);
assert.equal(applyEvent(first, { type: 'session_info_update', sessionFile: '/two.jsonl' }).questionDrafts, undefined);
console.log('提问草稿隔离、重试、迟到响应和会话结束检查通过');
