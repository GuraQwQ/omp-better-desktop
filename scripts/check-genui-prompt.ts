import assert from 'node:assert/strict';
import { genUIPrompt, acknowledgeGenUIPrompt, displayUserPrompt } from '../src/lib/genui-prompt';
import { normalizeGenUIConfiguration } from '../src/lib/genui-config';
import { createDraft, captureDraft, acknowledgeDraft } from '../src/lib/composer-draft';
const config = normalizeGenUIConfiguration(undefined);
assert.equal(genUIPrompt('test', '问题', config).message, '问题');
config.enabled = true; config.components = ['Text'];
const first = genUIPrompt('test', '问题', config);
assert(first.message.includes('Text'));
assert(!first.message.includes('Map('));
assert.equal(displayUserPrompt(first.message), '问题');
acknowledgeGenUIPrompt('test', first.key);
assert.equal(genUIPrompt('test', '下一条', config).message, '下一条');
config.features.showSource = true;
assert.equal(genUIPrompt('test', '查看源码后', config).message, '查看源码后');
config.components = ['Text', 'Input'];
assert.notEqual(genUIPrompt('test', '新配置', config).message, '新配置');
const typed = createDraft('尚未发送的草稿');
const action = captureDraft(createDraft('界面动作'));
acknowledgeDraft(action);
assert.equal(typed.text, '尚未发送的草稿');
console.log('生成式UI提示注入、配置变化与草稿保留检查通过');
