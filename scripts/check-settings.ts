import assert from 'node:assert/strict';
import { parseSettingInput, parseSettingLines, parseSettingRecord, settingApplicable, settingCategory, settingManagedInDesktop, settingMatches, settingOptionValues } from '../src/lib/settings-values';

assert.equal(parseSettingInput({ type: 'number' }, '0'), 0);
assert.throws(() => parseSettingInput({ type: 'number' }, ''));
assert.throws(() => parseSettingInput({ type: 'number' }, 'Infinity'));
assert.equal(parseSettingInput({ type: 'boolean' }, 'false'), false);
assert.equal(parseSettingInput({ type: 'boolean' }, 'true'), true);
assert.throws(() => parseSettingInput({ type: 'boolean' }, 'tru'));
assert.deepEqual(parseSettingInput({ type: 'array' }, '["甲"]'), ['甲']);
assert.throws(() => parseSettingInput({ type: 'array' }, '{}'));
assert.throws(() => parseSettingInput({ type: 'record' }, 'null'));
assert.throws(() => parseSettingInput({ type: 'record' }, '[]'));
assert.equal(settingCategory({ path: 'modelRoles' }), 'advanced');
assert.equal(settingCategory({ ui: { tab: 'model' } }), 'model');
assert(settingMatches({ path: 'compaction.enabled', ui: { label: 'Compaction' } }, 'COMPACTION', 'en'));
assert(settingMatches({ path: 'modelRoles' }, '模型', 'zh'));
assert.deepEqual(settingOptionValues({ ui: { options: [1, '1', true, 'true', { value: false, label: '关闭' }, null] } }), [1, '1', true, 'true', false]);
assert.deepEqual(settingOptionValues({ ui: { options: 'runtime' }, enumValues: [2, 3] }), [2, 3]);
assert.deepEqual(parseSettingRecord([{ key: '重命名', text: '42', type: 'number' }, { key: '开关', text: 'false', type: 'boolean' }]), { 重命名: 42, 开关: false });
assert.deepEqual(parseSettingRecord([{ key: '', text: '', type: 'string' }, { key: '提供商', text: '2', type: 'string' }], true), { 提供商: 2 });
assert.throws(() => parseSettingRecord([{ key: 'same', text: 'one', type: 'string' }, { key: ' same ', text: 'two', type: 'string' }]), /key/);
assert.throws(() => parseSettingRecord([{ key: '', text: '尚未命名', type: 'string' }]), /key/);
assert.throws(() => parseSettingRecord([{ key: 'number', text: '', type: 'number' }]), /number/);
assert.throws(() => parseSettingRecord([{ key: 'boolean', text: 'invalid', type: 'boolean' }]), /boolean/);
assert.deepEqual(parseSettingLines(''), []);
assert.deepEqual(parseSettingLines('甲\r\n\n乙\n'), ['甲', '', '乙', '']);
assert.deepEqual(parseSettingInput({ type: 'array' }, JSON.stringify(parseSettingLines('甲\n\n'))), ['甲', '', '']);
assert.equal(settingApplicable({ ui: { condition: 'hindsightActive' } }, { 'memory.backend': 'local' }), false);
assert.equal(settingApplicable({ ui: { condition: 'hindsightActive' } }, { 'memory.backend': 'hindsight' }), true);
assert.equal(settingApplicable({ ui: { condition: 'unknown' } }, {}), true);
assert.equal(settingManagedInDesktop({ path: 'skills.enableCodexUser' }), false);
assert.equal(settingManagedInDesktop({ path: 'skills.customDirectories' }), false);
assert.equal(settingManagedInDesktop({ path: 'skills.enabled' }), true);
console.log('设置输入、分类、字典类型、重复键和数组检查通过');
