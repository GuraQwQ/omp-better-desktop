import assert from 'node:assert/strict';
import { matchesShortcut, shortcuts } from '../src/lib/desktop-preferences';
import { parseReview, reviewPrompt } from '../src/lib/review';
import { describeCommand } from '../src/lib/command-descriptions';
import { taskCardSummary } from '../src/lib/task-card';
assert.equal(taskCardSummary('表单已准备\n```openui\nroot = Col([])\n```\n请确认。'), '表单已准备\n\n请确认。');
assert.equal(taskCardSummary('```genui-html\n<h2>表单</h2>'), '');
assert.equal(taskCardSummary('```ts\nconst a = 1;\n```\n```html\n<h2>内容</h2>\n```'), '');
assert(matchesShortcut({ key: 'F', ctrlKey: true, metaKey: false, shiftKey: true, altKey: false }, shortcuts.search.value));
assert(!matchesShortcut({ key: 'f', ctrlKey: true, metaKey: false, shiftKey: false, altKey: false }, shortcuts.search.value));
assert(!matchesShortcut({ key: 'n', ctrlKey: true, metaKey: false, shiftKey: false, altKey: false }, ''));
const report = parseReview('说明\n```review\n{"summary":"两项","issues":[{"id":"1","title":"丢失草稿","severity":"P1","evidence":"写入失败后清空","suggestion":"保留输入"},{"title":"旧回包","evidence":"覆盖当前项目"}]}\n```');
assert.equal(report.issues.length, 2);
assert.equal(report.issues[1].status, 'open');
assert(reviewPrompt(report.issues[0], true).includes('复验'));
assert.throws(() => parseReview('{"issues":[{"title":"缺少证据"}]}'));
assert.equal(describeCommand({ name: 'review', source: 'extension', description: 'Launch interactive code review' }, 'zh'), '开始交互式代码评审');
assert.equal(describeCommand({ name: 'review', source: 'extension', description: 'My custom review' }, 'zh'), 'My custom review');
console.log('快捷键匹配、评审解析与复验上下文检查通过');
