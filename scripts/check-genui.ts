import assert from 'node:assert/strict';
import { createStreamingParser } from '@openuidev/react-lang';
import { buildGenUIInstructions, genUIConfigurationKey, genUIRuntimeConfigurationKey, normalizeGenUIConfiguration } from '../src/lib/genui-config';
import { collectGenUIRepairs, extractGenUIBlocks, genUIRepairTarget, genUIRevision, resolveGenUIRepair, safeGenUIUrl } from '../src/lib/genui';
import { createGenUILibrary } from '../src/components/genui-openui';

const defaults = normalizeGenUIConfiguration();
assert.equal(defaults.enabled, false);
assert.equal(defaults.features.persistence, false);
assert.equal(defaults.features.streaming, false);
assert.equal(defaults.features.showSource, false);
assert.equal(defaults.components.includes('Map'), false);
assert.equal(buildGenUIInstructions(defaults), '');
const minimal = normalizeGenUIConfiguration({ enabled: true, components: ['Text', 'Col', 'Input', 'Button', 'Text', 'Unknown'], capabilities: [], features: { hostCalls: false, state: false, actions: false, html: false } });
const instructions = buildGenUIInstructions(minimal);
const sourceVisible = { ...minimal, features: { ...minimal.features, showSource: true } };
assert.equal(buildGenUIInstructions(sourceVisible), instructions);
assert.equal(genUIRuntimeConfigurationKey(sourceVisible), genUIRuntimeConfigurationKey(minimal));
assert.notEqual(genUIConfigurationKey(sourceVisible), genUIConfigurationKey(minimal));
assert.equal(instructions.includes('Map('), false);
assert.equal(instructions.includes('Query('), false);
assert.equal(instructions.includes('reactive'), false);
assert.equal(instructions.includes('genui-html'), false);
assert.equal(instructions.includes('action?'), false);
const library = createGenUILibrary(minimal);
assert.deepEqual(Object.keys(library.components), ['Col', 'Text', 'Input', 'Button']);
const parser = createStreamingParser(library.toJSONSchema());
const valid = parser.set('root = Col([Text("你好"), Input("name", "姓名", "王")])', true);
assert.ok(valid.root);
assert.equal(valid.meta.errors.length, 0);
const rejected = parser.set('root = Map(10, 20)', true);
assert.ok(rejected.meta.errors.length);
const full = createStreamingParser(createGenUILibrary({ ...defaults, enabled: true }).toJSONSchema());
const interactive = full.set('$name = "初始"\nfield = Input("name", "姓名", $name)\nsubmit = Button("保存", @ToAssistant("保存表单"))\nroot = Col([field, submit])', true);
assert.equal(interactive.meta.errors.length, 0);
assert.equal(interactive.stateDeclarations.$name, '初始');
assert.ok(interactive.root);
assert.equal(extractGenUIBlocks('```md\n```openui\nroot=Text("忽略")\n```\n').length, 0);
const blocks = extractGenUIBlocks('说明\n~~~openui\nroot = Text("中文")\n~~~\n```genui-html\n<p>HTML</p>');
assert.equal(blocks.length, 2);
assert.equal(blocks[0].complete, true);
assert.equal(blocks[0].source, 'root = Text("中文")');
assert.equal(blocks[1].complete, false);
assert.equal(genUIRepairTarget('<!-- omp-genui-target: message-1-0 -->\n<p>修复</p>'), 'message-1-0');
const original = blocks[0];
const repairText = '```openui\n// omp-genui-target: view\n// omp-genui-base: ' + genUIRevision(original.source) + '\nroot=Text("修复")\n```';
const repairs = collectGenUIRepairs([repairText]);
assert.ok(resolveGenUIRepair(original,repairs.view));
assert.equal(resolveGenUIRepair({ ...original, source: 'root=Text("新版本")' },repairs.view),undefined);
assert.equal(safeGenUIUrl('javascript:alert(1)'), undefined);
assert.equal(safeGenUIUrl('data:text/html,test'), undefined);
assert.ok(safeGenUIUrl('https://example.com'));
console.log('生成式 UI 配置、组件注册、OpenUI 解析、状态绑定与围栏检查通过。');
