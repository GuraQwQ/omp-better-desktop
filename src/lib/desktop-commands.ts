import type { Bootstrap, CatalogEntry, Json, Message, Preferences, Project, RuntimeRecord, SessionSummary } from './types';
import type { ComposerAttachment } from './attachments';
import type { GenUIKind } from './genui';
import type { SavedGenUI } from './genui-state';
import type { ModelCatalogResult } from './model-catalog';
import type { SessionStats } from '../generated/rpc-wire';

type Command<Input, Output> = { input: Input; output: Output };
type Empty = Record<string, never>;
type Cwd = { cwd: string };
type Id = { id: string };
type FilePath = { path: string };
type Page<T> = { items: T[]; total: number; nextCursor: string | null; warnings?: { error: string; path?: string }[] };
type HistoryPage = { messages: Message[]; nextCursor?: string | null; afterCursor?: string | null };
type ArchivedSession = SessionSummary & { missing?: boolean };
type ExternalSource = 'codex' | 'zcode';
type ExternalSession = SessionSummary & { source: ExternalSource; format: string };
type FileValue = { content: string; revision: string; encoding: string; newline: string };
type GitItem = { path: string; original?: string; status: string; staged: boolean; unstaged: boolean };
type GitStatus = { items: GitItem[] };
type Worktree = { path: string; branch?: string; head?: string; detached?: boolean; locked?: boolean };
type Shell = { id: string; cwd: string; name: string; running: boolean };
type CaptureStatus = { enabled: boolean; supported: boolean; directory: string; count: number; bytes: number; maxBytes: number; maxRecords: number };
type CaptureRecord = { id: string; createdAt: number; method: string; url: string; bytes: number; sessionId?: string | null; sessionPath?: string | null };
type Provider = { id: string; api: string; baseUrl: string; hasApiKey: boolean; models: (Json & { id: string })[]; options: Json };
type ProviderConfiguration = { configPath: string; takeover: { enabled: boolean; active: boolean; unknown?: boolean }; providers: Provider[]; savedProvider?: string; refreshErrors?: string[] };
type ProviderInput = { id: string; api?: string; baseUrl?: string; apiKey?: string; options?: Json; modelIds?: string[]; modelSettings?: Record<string, Json> };
type Usage = { tokens: { total: number; input: number; output: number; cacheRead: number; cacheWrite: number; reasoning: number }; cost: number; missingCost: number; messages: number; sessions: number };
type UsageSummary = { totals: Usage; models: { key: string; usage: Usage }[]; projects: { key: string; usage: Usage }[]; days: { key: string; usage: Usage }[]; warnings: { error: string; path: string }[] };
type ScheduleJob = { id?: string; name: string; cwd: string; prompt: string; nextAt: number; intervalMinutes?: number | null; enabled?: boolean };
type ScheduleRun = { runId: string; job: ScheduleJob; status: string; claimedAt: number; startedAt?: number | null; sessionId?: string | null; path?: string | null; error?: string | null };
type ImportResult = { source: string; target: string; copied: number; skipped: number; completed: boolean; retryable: boolean; conflicts: string[]; message?: string };
type LaunchProfile = { systemPrompt: string; appendSystemPrompt: string; addDirs: string[]; tools: string[]; profile: string; config: string[]; sessionDir: string; noRules: boolean; noLsp: boolean; noTools: boolean; planYolo: boolean };

export interface DesktopCommands {
  bootstrap: Command<Empty, Bootstrap>;
  'preferences.set': Command<{ patch: Partial<Preferences> }, Preferences>;
  'runtime.install': Command<FilePath, RuntimeRecord>;
  'runtime.rollback': Command<Empty, RuntimeRecord>;
  'runtime.clean': Command<Empty, { removed: string[] }>;
  'data.discover': Command<Empty, (FilePath & { sessionCount: number; profiles: string[]; kind: string; warning?: string | null })[]>;
  'data.import': Command<FilePath, ImportResult>;
  'data.takeover': Command<{ enabled: boolean }, { enabled: boolean; active: boolean; restartTerminal?: boolean }>;
  'launch.get': Command<Cwd, LaunchProfile>;
  'launch.set': Command<Cwd & { profile: Partial<LaunchProfile> }, LaunchProfile>;
  'requests.status': Command<Empty, CaptureStatus>;
  'requests.configure': Command<{ enabled: boolean }, CaptureStatus>;
  'requests.list': Command<{ sessionId?: string; path?: string }, CaptureRecord[]>;
  'requests.read': Command<Id, Json>;
  'requests.clear': Command<Empty, CaptureStatus>;
  'providers.config': Command<Cwd & ({ operation: 'list' } | { operation: 'save'; provider: ProviderInput } | { operation: 'delete'; provider: { id: string } }), ProviderConfiguration>;
  'providers.discover': Command<Cwd & { provider: ProviderInput }, Json>;
  'project.add': Command<FilePath, Project[]>;
  'project.remove': Command<FilePath, Project[]>;
  'attachment.paths': Command<{ paths: string[] }, ComposerAttachment[]>;
  'attachment.store': Command<{ name: string; data: string }, Extract<ComposerAttachment, { type: 'file' }>>;
  'attachment.clipboard': Command<Empty, ComposerAttachment[]>;
  'attachment.discard': Command<FilePath & { managed: boolean }, null>;
  'attachment.btw': Command<{ message: string; attachments: ComposerAttachment[] }, { message: string; images: { type: 'image'; data: string; mimeType: string }[]; warnings: string[] }>;
  'models.list': Command<Cwd & { refresh?: boolean }, ModelCatalogResult>;
  'session.list': Command<{ cwd?: string }, SessionSummary[]>;
  'session.search': Command<{ query: string; cwd?: string; includeArchived?: boolean; cursor?: string; limit?: number }, Page<{ session: ArchivedSession; messageId: string; role: string; snippet: string }>>;
  'session.locate': Command<FilePath & { messageId?: string; limit?: number }, HistoryPage>;
  'session.after': Command<FilePath & { cursor: string; limit?: number }, HistoryPage>;
  'session.archive': Command<FilePath & { archived: boolean }, FilePath & { archived: boolean }>;
  'session.pin': Command<FilePath & { pinned: boolean }, FilePath & { pinned: boolean }>;
  'session.reorder': Command<{ paths: string[] }, { paths: string[] }>;
  'session.archives': Command<Empty, ArchivedSession[]>;
  'session.delete': Command<FilePath, FilePath & { deleted: boolean; missing: boolean; warning?: string | null }>;
  'session.history': Command<FilePath & { cursor?: string; messageId?: string; limit?: number }, HistoryPage>;
  'session.stats': Command<FilePath, SessionStats>;
  'session.activate': Command<{ id: string | null }, null>;
  'session.open': Command<Cwd & { path?: string }, { id: string; cwd: string; path: string | null; state: Json }>;
  'session.rpc': Command<Id & { command: Json }, Json>;
  'swarm.control': Command<Id & { action: 'status' | 'enable' | 'disable' | 'create' | 'add' | 'post' | 'stop' | 'resume'; args?: Json }, Json>;
  'session.ui': Command<Id & { response: Json }, null>;
  'session.close': Command<Id, { path: string | null }>;
  'usage.summary': Command<{ cwd?: string; from?: string; to?: string }, UsageSummary>;
  'external.sessions': Command<{ source: ExternalSource; home?: string; query?: string; cwd?: string; cursor?: string; limit?: number }, Page<ExternalSession> & { home: string }>;
  'external.history': Command<{ source: ExternalSource; home?: string; path: string; id?: string; cursor?: string; limit?: number }, { messages: Message[]; nextCursor: string | null; total: number; warnings: { error: string }[] }>;
  'workspace.files': Command<Cwd, string[]>;
  'workspace.read': Command<Cwd & FilePath, string>;
  'workspace.diff': Command<Cwd, { diff: string; status: string }>;
  'workspace.search': Command<Cwd & { query: string; requestId: string; caseSensitive?: boolean; limit?: number }, { matches: { path: string; line: number; text: string }[]; truncated: boolean; cancelled: boolean; skipped: number; errors?: string[] }>;
  'workspace.search.cancel': Command<{ requestId: string }, null>;
  'file.get': Command<Cwd & FilePath, FileValue>;
  'file.preview': Command<FilePath, FileValue & { readOnly: true }>;
  'file.save': Command<Cwd & FilePath & { content: string; baseRevision: string }, FileValue>;
  'git.status': Command<Cwd, GitStatus>;
  'git.diff': Command<Cwd & { path?: string; staged?: boolean }, { diff: string }>;
  'git.stage': Command<Cwd & { paths: string[] }, GitStatus>;
  'git.unstage': Command<Cwd & { paths: string[] }, GitStatus>;
  'git.commit': Command<Cwd & { message: string }, { output: string; status: GitStatus }>;
  'worktree.list': Command<Cwd, Worktree[]>;
  'worktree.add': Command<Cwd & FilePath & { branch?: string; ref?: string }, { path: string; branch: string }>;
  'worktree.remove': Command<Cwd & FilePath, Worktree[]>;
  'shell.list': Command<{ cwd?: string }, Shell[]>;
  'shell.open': Command<Cwd & { name?: string; cols?: number; rows?: number }, Shell>;
  'shell.read': Command<Id, { data: string; seq: number; running: boolean }>;
  'shell.rename': Command<Id & { name: string }, Shell>;
  'shell.write': Command<Id & { data: string }, null>;
  'shell.resize': Command<Id & { cols: number; rows: number }, null>;
  'shell.close': Command<Id, null>;
  'artifact.list': Command<Cwd, { items: Json[] }>;
  'artifact.add': Command<Cwd & FilePath & { name?: string }, { items: Json[] }>;
  'artifact.read': Command<Id, Json>;
  'artifact.remove': Command<Id, null>;
  'layout.get': Command<{ key: string }, unknown>;
  'layout.set': Command<{ key: string; value: unknown }, unknown>;
  'desktop.state.get': Command<{ key: string }, unknown>;
  'desktop.state.set': Command<{ key: string; value: unknown }, unknown>;
  'schedule.list': Command<Empty, { jobs: (ScheduleJob & { id: string })[]; runs: ScheduleRun[] }>;
  'schedule.save': Command<{ job: ScheduleJob }, ScheduleJob>;
  'schedule.remove': Command<Id, null>;
  'schedule.claim': Command<{ now?: number }, { runId: string; job: ScheduleJob & { id: string } }[]>;
  'schedule.started': Command<{ runId: string; sessionId: string; path?: string }, null>;
  'schedule.finish': Command<{ runId: string; status: 'completed' | 'error' | 'interrupted'; error?: string }, null>;
  'schedule.recover': Command<Empty, { recovered: number }>;
  'schedule.retry': Command<{ runId: string }, ScheduleJob | { running: true }>;
  'export.markdown': Command<FilePath & { content?: string; sessionPath?: string; messages?: Message[]; title?: string; mode?: string; overwrite?: boolean; baseRevision?: string }, { path: string; existing?: boolean; revision?: string; count?: number }>;
  'browser.open': Command<{ url: string }, { url: string }>;
  'card.list': Command<Empty, string[]>;
  'card.open': Command<Id & { value?: Json }, null>;
  'card.sync': Command<Id & { value: Json }, { open: boolean }>;
  'card.get': Command<Id, Json | null>;
  'card.focus': Command<Id & { sessionId?: string }, null>;
  'terminal.open': Command<Id & { cols?: number; rows?: number }, Id>;
  'terminal.write': Command<Id & { data: string }, null>;
  'terminal.resize': Command<Id & { cols: number; rows: number }, null>;
  'terminal.close': Command<Id, null>;
  'command.catalog': Command<Empty, CatalogEntry[]>;
  'command.cli': Command<Cwd & { args: string[] }, { stdout: string; stderr: string; code: number | null }>;
  'system.open_url': Command<{ url: string }, { url: string }>;
  'system.path_info': Command<FilePath, { isFile: boolean; isDirectory: boolean }>;
  'system.reveal_path': Command<FilePath, { isFile: boolean; isDirectory: boolean }>;
  'genui.get': Command<Id, SavedGenUI | null>;
  'genui.save': Command<Id & { source: string; kind: GenUIKind; state: Record<string, unknown>; baseRevision: string | null; configurationKey: string }, SavedGenUI | null>;
  'genui.clear': Command<Empty, { cleared: number }>;
  'genui.call': Command<Cwd & { capability: string; args: Record<string, unknown> }, Json>;
  'genui.document': Command<{ html: string; csp: string }, { token: string }>;
  'genui.document.release': Command<{ token: string }, null>;
}

export type DesktopCommand = keyof DesktopCommands;
export type DesktopRequestArgs<K extends DesktopCommand = DesktopCommand> = K extends DesktopCommand
  ? [type: K, ...fields: {} extends DesktopCommands[K]['input'] ? [fields?: DesktopCommands[K]['input']] : [fields: DesktopCommands[K]['input']]]
  : never;
